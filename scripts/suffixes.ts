import { writeFile } from "node:fs/promises";

const LIST_URL = "https://publicsuffix.org/list/public_suffix_list.dat";
const OUTPUT = "src/data/suffixes.ts";
const LINE_WIDTH = 120;
const INDENT = "    ";

function icannRules(list: string): string[] {
  const section = /===BEGIN ICANN DOMAINS===([\s\S]*?)===END ICANN DOMAINS===/.exec(list)?.[1];
  if (section === undefined) throw new Error("The Public Suffix List has no ICANN section");
  return section
    .split("\n")
    .map((line) => line.trim())
    .filter((line) => line !== "" && !line.startsWith("//"));
}

function ascii(rule: string): string {
  const marker = /^(?:\*\.|!)/.exec(rule)?.[0] ?? "";
  return marker + new URL(`http://${rule.slice(marker.length)}`).hostname;
}

function byTld(rules: string[]): Map<string, string[]> {
  const grouped = new Map<string, string[]>();
  for (const rule of rules.map(ascii)) {
    const dot = rule.lastIndexOf(".");
    if (dot === -1) continue;
    const tld = rule.slice(dot + 1);
    grouped.set(tld, [...(grouped.get(tld) ?? []), rule.slice(0, dot)]);
  }
  return new Map([...grouped].sort(([a], [b]) => a.localeCompare(b)));
}

function wrap(labels: string[]): string[] {
  const lines: string[] = [];
  for (const label of labels) {
    const last = lines.at(-1);
    if (last !== undefined && INDENT.length + last.length + 1 + label.length <= LINE_WIDTH) {
      lines[lines.length - 1] = `${last} ${label}`;
    } else {
      lines.push(label);
    }
  }
  return lines;
}

function entry(tld: string, labels: string[]): string {
  const key = /^[a-z]+$/.test(tld) ? tld : `"${tld}"`;
  const inline = `  ${key}: "${labels.join(" ")}",`;
  if (inline.length <= LINE_WIDTH) return inline;
  return [`  ${key}: \``, ...wrap(labels).map((line) => `${INDENT}${line}`), "  `,"].join("\n");
}

const response = await fetch(LIST_URL);
if (!response.ok) throw new Error(`${LIST_URL} returned HTTP ${response.status}`);
const grouped = byTld(icannRules(await response.text()));
const body = [...grouped].map(([tld, labels]) => entry(tld, labels)).join("\n");
await writeFile(
  OUTPUT,
  [
    "// Generated by `pnpm suffixes` from the ICANN section of the Public Suffix List; don't edit by hand.",
    "export const secondLevelSuffixes: Readonly<Record<string, string>> = {",
    body,
    "};",
    "",
  ].join("\n"),
);
console.log(`${OUTPUT}: ${grouped.size} TLDs with second-level suffixes`);
