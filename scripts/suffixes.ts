import { writeFile } from "node:fs/promises";

const LIST_URL = "https://publicsuffix.org/list/public_suffix_list.dat";
const OUTPUT = "src/data/suffixes.ts";
const LINE_WIDTH = 116;

function tldsWithSecondLevels(list: string): string[] {
  const section = /===BEGIN ICANN DOMAINS===([\s\S]*?)===END ICANN DOMAINS===/.exec(list)?.[1];
  if (section === undefined) throw new Error("The Public Suffix List has no ICANN section");
  const tlds = section
    .split("\n")
    .map((line) => line.trim())
    .filter((rule) => rule.includes(".") && !rule.startsWith("//"))
    .map((rule) => new URL(`http://${rule.slice(rule.lastIndexOf(".") + 1)}`).hostname);
  return [...new Set(tlds)].sort();
}

function wrap(tlds: string[]): string[] {
  const lines: string[] = [];
  for (const tld of tlds) {
    const last = lines.at(-1);
    if (last !== undefined && last.length + 1 + tld.length <= LINE_WIDTH) lines[lines.length - 1] = `${last} ${tld}`;
    else lines.push(tld);
  }
  return lines;
}

const response = await fetch(LIST_URL);
if (!response.ok) throw new Error(`${LIST_URL} returned HTTP ${response.status}`);
const tlds = tldsWithSecondLevels(await response.text());
await writeFile(
  OUTPUT,
  [
    "// Generated by `pnpm suffixes` from the ICANN section of the Public Suffix List; don't edit by hand.",
    "export const tldsWithSecondLevelSuffixes = `",
    ...wrap(tlds).map((line) => `  ${line}`),
    "`;",
    "",
  ].join("\n"),
);
console.log(`${OUTPUT}: ${tlds.length} TLDs with second-level suffixes`);
